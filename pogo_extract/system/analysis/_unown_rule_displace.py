"""Unown-rule displacement analysis applied collection-wide.

Question: for which (species, form) would a PLAIN kept ONLY by the top-3 cap
(variant_floor) be DISPLACED to Transfer if in-bag SHINIES counted toward the
per-form top-3 plain cap?

A plain is DISPLACEABLE iff its keep-reason set == EXACTLY {"variant_floor"}.
Reasons come from the FRESH policy_reasons.json (regenerated by keep_policy.py).

cf() = keep_policy form-fold, replicated EXACTLY from keep_policy.py.
_truly_plain() replicated EXACTLY from keep_policy.py.
"""
import sqlite3, json, os, sys
from collections import defaultdict, Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))   # .../pogo_extract
sys.path.insert(0, ROOT)
from pvp_iv_rule import pvid
from costume_forms import is_costume_form

DB = os.path.join(ROOT, 'pokemon.db')
REASONS = os.path.join(ROOT, 'system', 'analysis', 'policy_reasons.json')

c = sqlite3.connect(DB); c.row_factory = sqlite3.Row
rows = c.execute("SELECT * FROM pokemon WHERE in_bag=1").fetchall()

reasons = json.load(open(REASONS))   # {uid_hex: [reasons...]}

# ---- replicate cf() form-fold EXACTLY (keep_policy lines 125-139) ----
_REGSUF = ('_alolan', '_galarian', '_hisuian', '_paldean')
def _is_regional_code(nm, f):
    return any(x in pvid(nm, f) for x in _REGSUF)
_basecnt = defaultdict(Counter)
for r in rows:
    _f = r['form'] or 0
    _reg = (r['form_region'] or '').strip().lower()
    if _f != 0 and _reg in ('', 'normal', 'kantonian', 'none', 'null') and not _is_regional_code(r['species_name'], _f):
        _basecnt[r['pokemon_id']][_f] += 1
base_form = {pid: cnt.most_common(1)[0][0] for pid, cnt in _basecnt.items() if len(cnt) == 1}
def cf(r):
    _f = r['form'] or 0
    return base_form.get(r['pokemon_id'], _f) if _f == 0 else _f

# ---- replicate _truly_plain() EXACTLY (keep_policy lines 160-165) ----
def _truly_plain(r):
    return (not (r['fresh_costume'] or 0) and not (r['special_bg_id'] or 0)
            and not (r['natural_art_background'] or 0)
            and not (r['costume_decoration_id'] and str(r['costume_decoration_id']) != '0')
            and (r['fresh_bread_mode'] or 0) not in (1, 2)
            and not is_costume_form(r['fresh_form']))

# truly-plain definition (matches keep_policy 'plain' pool gate too):
# non-shiny, non-shadow (fresh_alignment!=1), and no cosmetic axis.
def is_plain_row(r):
    return r['fresh_alignment'] != 1 and not r['fresh_shiny'] and _truly_plain(r)

def is_shiny_displacer(r):
    return bool(r['fresh_shiny']) and (r['iv_total'] or 0) not in (0, 45)

# ---- build set K: displaceable plains (reason set EXACTLY {"variant_floor"}) ----
# and set S: displacer shinies, grouped by (pid, cf)
K = defaultdict(list)   # (pid,cf) -> [plain rows displaceable]
S = defaultdict(list)   # (pid,cf) -> [shiny displacer rows]
ALL_PLAIN_KEPT = defaultdict(list)  # for sanity: all variant_floor-only plains regardless

for r in rows:
    rs = set(reasons.get(r['uid_hex'], []))
    key = (r['pokemon_id'], cf(r))
    if is_plain_row(r) and rs == {'variant_floor'}:
        K[key].append(r)
    if is_shiny_displacer(r):
        S[key].append(r)

def iv_pct(iv):
    return round((iv or 0) / 45 * 100)

# ---- compute displacement per (pid, cf) ----
def sortkey(r):
    return (-(r['iv_total'] or 0), -(r['cp'] or 0))

instances = []
total_displaced = 0
LITERAL_displaced = 0   # the raw "K not in top3" count (for transparency vs gender-split artifact)
for key, kplains in K.items():
    sh = S.get(key, [])
    if not sh:
        continue   # no shiny to displace anything
    union = kplains + sh
    union_sorted = sorted(union, key=sortkey)
    top3 = union_sorted[:3]
    top3_ids = set(id(x) for x in top3)
    # literal (question's set-math) displaced -- includes plain-vs-plain bumping when |K|>3:
    lit = [r for r in kplains if id(r) not in top3_ids]
    LITERAL_displaced += len(lit)
    # INTENT-FAITHFUL displaced: a K-plain is displaced ONLY if a SHINY took its slot.
    # = K-plains out of top-3 that are outranked by >=1 shiny IN the top-3.
    # Equivalently: the lowest-IV K-plains bumped specifically by shinies cracking the top-3.
    shinies_in_top3 = [x for x in top3 if x['fresh_shiny']]
    n_shiny_top3 = len(shinies_in_top3)
    # plains that lose a slot to a shiny = the n_shiny_top3 lowest-IV K-plains
    # among those NOT in the top-3 (only those actually pushed out by a shiny).
    k_out = [r for r in kplains if id(r) not in top3_ids]
    # of the K-plains pushed out, the ones displaced *by shinies* are the lowest n_shiny_top3.
    # (if |K|<=3 every k_out is shiny-caused; if |K|>3 the highest k_out lost to plains, not shinies.)
    k_out_sorted = sorted(k_out, key=sortkey)            # best first
    displaced = k_out_sorted[len(k_out) - n_shiny_top3:] if n_shiny_top3 > 0 else []
    displaced = [d for d in displaced]                    # lowest n_shiny_top3
    if not displaced:
        continue
    # best displacer shiny iv = best IV among shinies that actually cracked the top-3.
    best_shiny_iv = max((s['iv_total'] or 0) for s in shinies_in_top3)
    lowest_disp_iv = min((d['iv_total'] or 0) for d in displaced)
    sp = displaced[0]['species_name']
    instances.append({
        'species': sp,
        'pokemon_id': key[0],
        'form': int(key[1]),
        'best_displacer_shiny_iv_pct': iv_pct(best_shiny_iv),
        'lowest_displaced_plain_iv_pct': iv_pct(lowest_disp_iv),
        'n_displaced': len(displaced),
        '_best_shiny_iv_raw': best_shiny_iv,
        '_lowest_disp_iv_raw': lowest_disp_iv,
        '_n_K': len(kplains),
        '_n_S': len(sh),
    })
    total_displaced += len(displaced)

instances.sort(key=lambda x: (x['pokemon_id'], x['form']))

# ---- reasons_accumulate check ----
# verified by code reading: keep=defaultdict(set); mark()=keep[uid].add(why) -> ACCUMULATES.
print("reasons_accumulate = True (keep=defaultdict(set), mark does .add())")
print(f"total uids in reasons file: {len(reasons)}")
print(f"variant_floor-only plain groups (|K| keys): {len(K)}")
print(f"groups with >=1 displacer shiny: {sum(1 for k in K if S.get(k))}")
print(f"TOTAL INSTANCES (>=1 displaced, shiny-caused): {len(instances)}")
print(f"TOTAL PLAIN DISPLACED (shiny-caused, intent-faithful): {total_displaced}")
print(f"  [literal set-math 'K not in top3' incl. gender plain-bumping: {LITERAL_displaced}]")
print()
for it in instances:
    print(f"  pid={it['pokemon_id']:>4} form={it['form']:>5} {it['species']:<16} "
          f"K={it['_n_K']} S={it['_n_S']} bestShinyIV={it['_best_shiny_iv_raw']}({it['best_displacer_shiny_iv_pct']}%) "
          f"lowDispIV={it['_lowest_disp_iv_raw']}({it['lowest_displaced_plain_iv_pct']}%) nDisp={it['n_displaced']}")

# emit JSON for programmatic capture
out = {
    'reasons_accumulate': True,
    'total_instances': len(instances),
    'total_plain_displaced': total_displaced,
    'instances': [{k: v for k, v in it.items() if not k.startswith('_')} for it in instances],
}
json.dump(out, open(os.path.join(HERE, '_unown_rule_displace_result.json'), 'w'), indent=2)
print("\nwrote _unown_rule_displace_result.json")
