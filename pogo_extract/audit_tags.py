"""Audit each server-side tag against current bag rules. Report drift.

Tag-rule mapping (verified 2026-05-27 against the live game):
  Hundos          iv_total=45
  Nundos          is_zero=1 AND pokemon_id!=0          (pid=0 = empty inventory slots; not real pokemon)
  Background      fresh_has_location_card=1
  Adventure Eff   adventure_effects_left>0             (was fresh_pokemon_badge!=0 — wrong column; zero overlap)
  JUMBO           pokemon_size_category=5              (5=XXL in PoGo's size enum; this IS the right rule)
  From Ethan      (is_traded_flag_v2=1 OR is_lucky=1) AND lower(original_owner_name)='ethanmateovz'
  From Florandez  (is_traded_flag_v2=1 OR is_lucky=1) AND lower(original_owner_name)='florandez'
  0-15-15         iv_atk=0 AND iv_def=15 AND iv_sta=15
  GL              gl_rank=1                            (gl_rank is per-(species,form), not global)
  UL              ul_rank=1                            (same; many distinct species qualify)
  Legacy          uid_hex in legacy_accurate.json      (gamemaster-driven; regen via detect_legacy.py)
  CLAUDE_TX       cull_decision_v9='TRANSFER'          (the cull's current transfer set)
  Evolve Me       MANUAL                               (user-curated; no derivable rule)
"""
import sqlite3, json, os

DB = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'pokemon.db')
LEGACY_JSON = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'legacy_accurate.json')

conn = sqlite3.connect(DB)
c = conn.cursor()

# Load legacy uids (gamemaster-authoritative, regenerated by detect_legacy.py).
legacy_uids = set()
if os.path.exists(LEGACY_JSON):
    try:
        legacy_uids = {e['uid_hex'] for e in json.load(open(LEGACY_JSON))}
    except (json.JSONDecodeError, KeyError):
        pass

def tag_set(name):
    """uid_hex set carrying the named tag in auth_tag_names (in-bag only)."""
    # Use ;-bounded LIKE so 'GL' doesn't match 'GL_premier', etc.
    pattern = '%' + name + '%'
    rows = c.execute(
        "SELECT uid_hex, auth_tag_names FROM pokemon WHERE in_bag=1 AND auth_tag_names LIKE ?",
        (pattern,)
    ).fetchall()
    return {uh for uh, txt in rows if name in (txt or '').split(';')}

def sql_rule_set(where):
    return {r[0] for r in c.execute(
        f"SELECT uid_hex FROM pokemon WHERE in_bag=1 AND ({where})"
    ).fetchall()}

# Each entry: (display_name, kind, rule)
# kind = 'sql' -> rule is a WHERE clause
# kind = 'uids' -> rule is a precomputed uid_hex set
# kind = 'manual' -> tag has no derivable rule; report members only
TAGS = [
    ('Hundos',         'sql', 'iv_total=45'),
    ('Nundos',         'sql', 'is_zero=1 AND pokemon_id!=0'),
    ('Background',     'sql', 'fresh_has_location_card=1'),
    ('Adventure Eff',  'sql', 'adventure_effects_left>0'),
    ('JUMBO',          'sql', 'pokemon_size_category=5'),
    ('From Ethan',     'sql', "(is_traded_flag_v2=1 OR is_lucky=1) AND lower(original_owner_name)='ethanmateovz'"),
    ('From Florandez', 'sql', "(is_traded_flag_v2=1 OR is_lucky=1) AND lower(original_owner_name)='florandez'"),
    ('0-15-15',        'sql', 'iv_atk=0 AND iv_def=15 AND iv_sta=15'),
    ('GL',             'sql', 'gl_rank=1'),
    ('UL',             'sql', 'ul_rank=1'),
    ('Legacy',         'uids', legacy_uids),
    ('CLAUDE_TX',      'sql', "cull_decision_v9='TRANSFER'"),
    ('Evolve Me',      'manual', None),
]


print(f'{"Tag":<16} {"In tag":>8} {"By rule":>8} {"Untagged":>10} {"Surplus":>9}  Notes')
print('-'*80)
for name, kind, rule in TAGS:
    tagged = tag_set(name)
    if kind == 'sql':
        expected = sql_rule_set(rule)
    elif kind == 'uids':
        expected = set(rule) if rule else set()
        if not rule:
            print(f'{name:<16} {len(tagged):>8} {"-":>8} {"-":>10} {"-":>9}  source file missing')
            continue
    else:  # manual
        print(f'{name:<16} {len(tagged):>8} {"-":>8} {"-":>10} {"-":>9}  manual tag; no derivable rule')
        continue
    untagged = expected - tagged
    surplus  = tagged   - expected
    note = ''
    if not expected and not tagged: note = 'empty'
    elif untagged or surplus:       note = 'DRIFT'
    print(f'{name:<16} {len(tagged):>8} {len(expected):>8} {len(untagged):>10} {len(surplus):>9}  {note}')

# Surface any live server-side tag we don't have a rule for. Future-proofing.
KNOWN = {n for n, _, _ in TAGS}
live_tags = set()
for (txt,) in c.execute("SELECT auth_tag_names FROM pokemon WHERE in_bag=1 AND auth_tag_names IS NOT NULL"):
    for nm in (txt or '').split(';'):
        nm = nm.strip()
        if nm: live_tags.add(nm)
unknown = sorted(live_tags - KNOWN)
print()
if unknown:
    print(f'WARNING: {len(unknown)} live server tag(s) have no rule defined in audit_tags.py:')
    for nm in unknown:
        n = len(tag_set(nm))
        print(f'   - {nm:24s} {n}')
else:
    print('All live server tags have a rule defined.')


# ---- drill-downs for tags with non-trivial drift ----

def drill(name, where_or_uids, kind='sql', limit=20):
    """Print up to `limit` rule-matching pokemon that are NOT carrying the tag."""
    tagged = tag_set(name)
    if kind == 'sql':
        rows = c.execute(
            f"""SELECT uid_hex, species_name, form, cp, iv_total, fresh_shiny, auth_tag_names
                FROM pokemon WHERE in_bag=1 AND ({where_or_uids})"""
        ).fetchall()
        untagged = [r for r in rows if r[0] not in tagged]
    else:
        in_clause = "('" + "','".join(where_or_uids) + "')" if where_or_uids else "('')"
        rows = c.execute(
            f"""SELECT uid_hex, species_name, form, cp, iv_total, fresh_shiny, auth_tag_names
                FROM pokemon WHERE in_bag=1 AND uid_hex IN {in_clause}"""
        ).fetchall()
        untagged = [r for r in rows if r[0] not in tagged]
    if not untagged: return
    print(f'\n=== {name}: {len(untagged)} rule-match but UNTAGGED (showing up to {limit}) ===')
    for r in untagged[:limit]:
        print(f'  {r[0]}  {r[1]:18s} form={r[2]:>4} cp={r[3]:4d} iv={r[4]:2d}/45 shiny={r[5]}  tags="{r[6] or ""}"')


def drill_surplus(name, where_or_uids, kind='sql', limit=20):
    """Print up to `limit` tagged pokemon that do NOT match the rule."""
    tagged = tag_set(name)
    if kind == 'sql':
        match = sql_rule_set(where_or_uids)
    else:
        match = set(where_or_uids)
    surplus = tagged - match
    if not surplus: return
    print(f'\n=== {name}: {len(surplus)} TAGGED but rule-mismatch (showing up to {limit}) ===')
    for uh in list(surplus)[:limit]:
        r = c.execute('SELECT species_name, form, cp, iv_total, auth_tag_names FROM pokemon WHERE uid_hex=?',
                      (uh,)).fetchone()
        print(f'  {uh}  {r[0]:18s} form={r[1]:>4} cp={r[2]:4d} iv={r[3]:2d}/45  tags="{r[4] or ""}"')


# Heaviest drift first — based on the May 2026 audit (UL/GL/CLAUDE_TX/Adventure Eff/Nundos).
drill('UL', 'ul_rank=1')
drill_surplus('UL', 'ul_rank=1')
drill('GL', 'gl_rank=1')
drill_surplus('GL', 'gl_rank=1')
drill('CLAUDE_TX', "cull_decision_v9='TRANSFER'")
drill_surplus('CLAUDE_TX', "cull_decision_v9='TRANSFER'")
drill('Adventure Eff', 'adventure_effects_left>0')
drill_surplus('Adventure Eff', 'adventure_effects_left>0')
drill('Nundos', 'is_zero=1 AND pokemon_id!=0')
drill('JUMBO', 'pokemon_size_category=5')
drill('Hundos', 'iv_total=45')

conn.close()
