def level_to_cpm(level):
    idx = int(round((level - 1) * 2))
    return cpms[idx]

# All half levels 1..51
LEVELS = [1 + 0.5*i for i in range(101)]

def stats(base_a, base_d, base_s, ia, idd, iss, level):
    cpm = level_to_cpm(level)
    a = (base_a + ia) * cpm
    de = (base_d + idd) * cpm
    s = (base_s + iss) * cpm
    return a, de, s, cpm

def cp(base_a, base_d, base_s, ia, idd, iss, level):
    a, de, s, cpm = stats(base_a, base_d, base_s, ia, idd, iss, level)
    return max(10, math.floor((a * math.sqrt(de) * math.sqrt(s)) / 10))

def best_for_cap(base_a, base_d, base_s, ia, idd, iss, cap, max_level):
    best = None
    for L in LEVELS:
        if L > max_level: break
        c = cp(base_a, base_d, base_s, ia, idd, iss, L)
        if c > cap:
            break
        a, de, s, cpm = stats(base_a, base_d, base_s, ia, idd, iss, L)
        sp = a * de * math.floor(s)         # PvPoke uses floor(hp) in product
        best = dict(level=L, cp=c, sp=sp, a=a, de=de, s=math.floor(s))
    return best

